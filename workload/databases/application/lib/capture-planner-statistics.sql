-- Capture the planner statistics (pg_statistic) of every table in schema
-- public as a replayable SQL script.
--
-- Run against the reference database with
--   psql -X -At -v ON_ERROR_STOP=1 -f capture-planner-statistics.sql > planner-statistics.sql
--
-- ANALYZE draws a random row sample for tables larger than the sample size
-- (300 x default_statistics_target rows), so statistics of large tables can
-- only be reproduced by restoring a recorded snapshot.  The generated script
-- deletes the current statistics of these tables and inserts the recorded
-- ones.  Array-typed statistic slots are rebuilt with array_in(), which yields
-- the pseudo-type anyarray that pg_statistic requires.
SET TimeZone = 'UTC';
SET DateStyle = 'ISO, YMD';
SET IntervalStyle = 'postgres';
SET extra_float_digits = 1;
SELECT '-- Recorded planner statistics for the application database (schema public).';
SELECT '-- Generated by capture-planner-statistics.sql; requires superuser.';
SELECT 'SET TimeZone = ''UTC'';';
SELECT 'SET DateStyle = ''ISO, YMD'';';
SELECT 'SET extra_float_digits = 1;';
SELECT 'BEGIN;';
SELECT format('DELETE FROM pg_catalog.pg_statistic WHERE starelid = %L::regclass;', 'public.' || c.relname)
FROM pg_class c
WHERE c.relnamespace = 'public'::regnamespace
  AND EXISTS (SELECT 1 FROM pg_statistic s WHERE s.starelid = c.oid)
ORDER BY c.relname;
WITH s AS (
  SELECT c.relname, a.attname, a.atttypid, t.typelem, st.*,
         st.stavalues1::text AS v1, st.stavalues2::text AS v2, st.stavalues3::text AS v3,
         st.stavalues4::text AS v4, st.stavalues5::text AS v5
  FROM pg_statistic st
  JOIN pg_class c ON c.oid = st.starelid
  JOIN pg_attribute a ON a.attrelid = st.starelid AND a.attnum = st.staattnum
  JOIN pg_type t ON t.oid = a.atttypid
  WHERE c.relnamespace = 'public'::regnamespace
)
SELECT format(
  'INSERT INTO pg_catalog.pg_statistic VALUES (%L::regclass, (SELECT attnum FROM pg_attribute WHERE attrelid = %L::regclass AND attname = %L), %L, %s::real, %s, %s::real, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s);',
  'public.' || relname, 'public.' || relname, attname, stainherit,
  stanullfrac::text, stawidth, stadistinct::text,
  stakind1, stakind2, stakind3, stakind4, stakind5,
  CASE WHEN staop1 = 0 THEN '0' ELSE quote_literal(staop1::regoperator::text) || '::regoperator' END,
  CASE WHEN staop2 = 0 THEN '0' ELSE quote_literal(staop2::regoperator::text) || '::regoperator' END,
  CASE WHEN staop3 = 0 THEN '0' ELSE quote_literal(staop3::regoperator::text) || '::regoperator' END,
  CASE WHEN staop4 = 0 THEN '0' ELSE quote_literal(staop4::regoperator::text) || '::regoperator' END,
  CASE WHEN staop5 = 0 THEN '0' ELSE quote_literal(staop5::regoperator::text) || '::regoperator' END,
  CASE WHEN stacoll1 = 0 THEN '0' ELSE quote_literal(stacoll1::regcollation::text) || '::regcollation' END,
  CASE WHEN stacoll2 = 0 THEN '0' ELSE quote_literal(stacoll2::regcollation::text) || '::regcollation' END,
  CASE WHEN stacoll3 = 0 THEN '0' ELSE quote_literal(stacoll3::regcollation::text) || '::regcollation' END,
  CASE WHEN stacoll4 = 0 THEN '0' ELSE quote_literal(stacoll4::regcollation::text) || '::regcollation' END,
  CASE WHEN stacoll5 = 0 THEN '0' ELSE quote_literal(stacoll5::regcollation::text) || '::regcollation' END,
  coalesce(quote_literal(stanumbers1::text) || '::real[]', 'NULL'),
  coalesce(quote_literal(stanumbers2::text) || '::real[]', 'NULL'),
  coalesce(quote_literal(stanumbers3::text) || '::real[]', 'NULL'),
  coalesce(quote_literal(stanumbers4::text) || '::real[]', 'NULL'),
  coalesce(quote_literal(stanumbers5::text) || '::real[]', 'NULL'),
  -- MCELEM slots (kind 4) hold array elements; all other value slots hold
  -- values of the column type.
  coalesce(format('array_in(%L, %L::regtype, -1)', v1, (CASE WHEN stakind1 = 4 THEN typelem ELSE atttypid END)::regtype::text), 'NULL'),
  coalesce(format('array_in(%L, %L::regtype, -1)', v2, (CASE WHEN stakind2 = 4 THEN typelem ELSE atttypid END)::regtype::text), 'NULL'),
  coalesce(format('array_in(%L, %L::regtype, -1)', v3, (CASE WHEN stakind3 = 4 THEN typelem ELSE atttypid END)::regtype::text), 'NULL'),
  coalesce(format('array_in(%L, %L::regtype, -1)', v4, (CASE WHEN stakind4 = 4 THEN typelem ELSE atttypid END)::regtype::text), 'NULL'),
  coalesce(format('array_in(%L, %L::regtype, -1)', v5, (CASE WHEN stakind5 = 4 THEN typelem ELSE atttypid END)::regtype::text), 'NULL'))
FROM s
ORDER BY relname, staattnum, stainherit;
SELECT 'COMMIT;';
