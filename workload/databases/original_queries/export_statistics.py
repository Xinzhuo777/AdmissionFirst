#!/usr/bin/env python3
"""Export the planner statistics of schema public as a replayable SQL script.

PostgreSQL 16 ANALYZE samples rows at random, so two builds with identical data get
slightly different pg_statistic contents and reltuples estimates, and some query plans
differ.  This tool writes, for every table and index of schema public, the pg_class
reltuples estimate and every pg_statistic row as SQL that a superuser can replay on
another build of the same database (sql/recorded_statistics.sql was produced this way
from the database used for the paper's measurements).

Usage: python3 export_statistics.py --psql PSQL --host SOCKET_DIR --port PORT \
           --dbname DB --output recorded_statistics.sql

Python 3 standard library only; talks to the server through psql as user postgres.
"""
import argparse
import json
import os
import subprocess
import sys

QUERY = r"""
SELECT json_build_object(
  'rel', c.relname, 'attnum', s.staattnum, 'att', a.attname,
  'elemtype', format_type(a.atttypid, NULL),
  'inherit', s.stainherit, 'nullfrac', s.stanullfrac::text, 'width', s.stawidth,
  'distinct', s.stadistinct::text,
  'kinds', ARRAY[s.stakind1, s.stakind2, s.stakind3, s.stakind4, s.stakind5],
  'ops', ARRAY[s.staop1::regoperator::text, s.staop2::regoperator::text,
               s.staop3::regoperator::text, s.staop4::regoperator::text,
               s.staop5::regoperator::text],
  'opoids', ARRAY[s.staop1, s.staop2, s.staop3, s.staop4, s.staop5],
  'colls', ARRAY[s.stacoll1::regcollation::text, s.stacoll2::regcollation::text,
                 s.stacoll3::regcollation::text, s.stacoll4::regcollation::text,
                 s.stacoll5::regcollation::text],
  'colloids', ARRAY[s.stacoll1, s.stacoll2, s.stacoll3, s.stacoll4, s.stacoll5],
  'numbers', ARRAY[s.stanumbers1::text, s.stanumbers2::text, s.stanumbers3::text,
                   s.stanumbers4::text, s.stanumbers5::text],
  'values', ARRAY[s.stavalues1::text, s.stavalues2::text, s.stavalues3::text,
                  s.stavalues4::text, s.stavalues5::text])
FROM pg_statistic s
JOIN pg_class c ON c.oid = s.starelid
JOIN pg_attribute a ON a.attrelid = s.starelid AND a.attnum = s.staattnum
WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r'
ORDER BY c.relname, s.staattnum, s.stainherit
"""

RELQUERY = r"""
SELECT json_build_object('rel', relname, 'kind', relkind, 'reltuples', reltuples::text)
FROM pg_class WHERE relnamespace = 'public'::regnamespace AND relkind IN ('r', 'i')
ORDER BY relname
"""


def run(args, sql):
    env = {k: v for k, v in os.environ.items() if not k.startswith('PG')}
    env['PGCLIENTENCODING'] = 'UTF8'
    env['PGOPTIONS'] = '-c extra_float_digits=1'
    out = subprocess.run([args.psql, '-X', '--no-password', '-v', 'ON_ERROR_STOP=1',
                          '-h', args.host, '-p', str(args.port), '-U', 'postgres',
                          '-d', args.dbname, '-At', '-c', sql],
                         check=True, stdout=subprocess.PIPE, env=env).stdout
    return [json.loads(line) for line in out.decode('utf-8').splitlines() if line]


def lit(value):
    if value is None:
        return 'NULL'
    return "'" + value.replace("'", "''") + "'"


def regclass(name):
    return lit('public.' + '"' + name.replace('"', '""') + '"') + '::regclass'


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--psql', default='psql')
    parser.add_argument('--host', default='/tmp')
    parser.add_argument('--port', default='5432')
    parser.add_argument('--dbname', required=True)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    stats = run(args, QUERY)
    rels = run(args, RELQUERY)
    lines = [
        '-- Planner statistics of the database used for the paper\'s measurements: the',
        '-- pg_class.reltuples estimate of every table and index in schema public and every',
        '-- pg_statistic row of those tables, as produced by its one VACUUM (FREEZE, ANALYZE).',
        '-- Optional: replaying this after build.sh (build.sh --recorded-statistics) replaces the',
        '-- randomly sampled statistics of a new build with the recorded ones, so the planner sees',
        '-- exactly the same statistics.  Generated by export_statistics.py; do not edit.',
        '',
        '\\set ON_ERROR_STOP on',
        "SET client_encoding = 'UTF8';",
        'BEGIN;',
    ]
    for rel in rels:
        lines.append('UPDATE pg_catalog.pg_class SET reltuples = %s WHERE oid = %s;'
                     % (rel['reltuples'], regclass(rel['rel'])))
    lines.append('DELETE FROM pg_catalog.pg_statistic WHERE starelid IN (SELECT oid FROM '
                 "pg_catalog.pg_class WHERE relnamespace = 'public'::regnamespace AND relkind = 'r');")
    for row in stats:
        ops = ['0' if int(oid) == 0 else '%s::regoperator' % lit(name)
               for name, oid in zip(row['ops'], row['opoids'])]
        colls = ['0' if int(oid) == 0 else '%s::regcollation' % lit(name)
                 for name, oid in zip(row['colls'], row['colloids'])]
        numbers = ['NULL' if n is None else '%s::real[]' % lit(n) for n in row['numbers']]
        values = ['NULL' if v is None else 'array_in(%s, %s::regtype, -1)'
                  % (lit(v), lit(row['elemtype'])) for v in row['values']]
        lines.append(
            'INSERT INTO pg_catalog.pg_statistic VALUES (%s, %d, %s, %s, %d, %s, %s, %s, %s, %s, %s);'
            % (regclass(row['rel']), row['attnum'], 'true' if row['inherit'] else 'false',
               row['nullfrac'], row['width'], row['distinct'],
               ', '.join(str(k) for k in row['kinds']), ', '.join(ops), ', '.join(colls),
               ', '.join(numbers), ', '.join(values)))
    lines.append('COMMIT;')
    with open(args.output, 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(lines) + '\n')
    print('%d relations, %d pg_statistic rows written to %s' % (len(rels), len(stats), args.output))
    return 0


if __name__ == '__main__':
    sys.exit(main())
